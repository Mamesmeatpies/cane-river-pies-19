const stateAbbreviations: Record<string, string> = {
  ARKANSAS: "AR",
  LOUISIANA: "LA",
  MISSISSIPPI: "MS",
  OKLAHOMA: "OK",
  TEXAS: "TX",
};

const uppercaseWords = new Set(["CT", "E", "FM", "HWY", "I", "JR", "LA", "MLK", "N", "NW", "RD", "S", "SR", "ST", "SW", "US", "USHWY", "W"]);

const toTitleCase = (value: string) =>
  value
    .split(" ")
    .map((word) => {
      if (uppercaseWords.has(word) || /^\d+$/.test(word)) {
        return word;
      }

      return word
        .toLowerCase()
        .replace(/(^|[-'])([a-z])/g, (_, prefix: string, letter: string) => `${prefix}${letter.toUpperCase()}`);
    })
    .join(" ");

export type StoreLocation = {
  storeNumber: string;
  storeName: string;
  address: string;
  city: string;
  state: string;
  stateAbbreviation: string;
  label: string;
};

export const storeLocations: StoreLocation[] = storeLocationRows.split("\n").map((row) => {
  const [storeNumber, storeName, city, state] = row.split("\t");
  const stateAbbreviation = stateAbbreviations[state] ?? state;
  const formattedStoreName = toTitleCase(storeName);
  const formattedCity = toTitleCase(city);

  return {
    storeNumber,
    storeName: formattedStoreName,
    address: formattedStoreName,
    city: formattedCity,
    state: toTitleCase(state),
    stateAbbreviation,
    label: `#${storeNumber} - ${formattedStoreName}, ${formattedCity}, ${stateAbbreviation}`,
  };
});
